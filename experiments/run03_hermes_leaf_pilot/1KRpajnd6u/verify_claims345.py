"""verify_claims345.py — records the feasibility assessment for the three empirical
table claims (3: Table 3 shallow water, 4: Table 4 traffic, 5: Table 5 spinodal).

These claims are NOT reproducible within this budget. This script does not fabricate any
substitute number; it records the concrete blockers it checked and emits
results/claim3.json, results/claim4.json, results/claim5.json with verdict "inconclusive".

Run: .venv/bin/python verify_claims345.py
"""
import json, os, re, subprocess, sys

PAPER_TXT = "/tmp/paper.txt"   # the single paper read; may be absent on re-run

blockers_common = [
    "No code repository URL appears anywhere in the paper text (searched for 'github', "
    "'zenodo', 'anonymous.4open', 'code is available' -> zero hits).",
    "No dataset URL or dataset-generation script is provided; all four benchmarks use "
    "simulation data generated by the authors with unpublished solver settings.",
    "Reproducing the number requires full pushforward training (AdamW, K-step unroll) of "
    "both a ResNet and an FNO backbone plus 3-4 baselines, multi-seed, which is far outside "
    "an 8h CPU budget even if the data existed.",
]

claims = {
    3: {
        "claim": "Table 3: FluxNet-LAP depth MAE 3.12e-3 vs 6.74e-3 for the best baseline "
                 "(Box+Mass projection); conservation error 3.3e-7 -> 3.3e-8.",
        "source": "Section 4.2, Table 3",
        "quoted_numbers": {"fluxnet_lap_h_mae_e-3": 3.12, "best_projection_baseline_h_mae_e-3": 6.74,
                           "baseline_econs": 3.3e-7, "fluxnet_econs": 3.3e-8},
        "extra_blockers": [
            "The 2D shallow-water dataset (dry regions, periodic BC, specific IC family) is not "
            "released and its generation parameters are not stated in the main text.",
            "Note for the reader: 3.12e-3 is the ResNet-backbone FluxNet-LAP entry while 6.74e-3 "
            "is the FNO-backbone Box+Mass projection entry; within the ResNet backbone the "
            "projection baseline is 22.1e-3, and within the FNO backbone FluxNet-LAP is 2.22e-3. "
            "The comparison as anchored crosses backbone categories.",
        ],
        "what_is_covered_elsewhere": "The structural half (conservation error at the 1e-7..1e-8 "
                                     "level) is established generically by claim 1.",
    },
    4: {
        "claim": "Table 4: FluxNet-D MAE 3.48e-3 vs 15.9e-3 CNN-AR; conservation error 2.1e-2 -> "
                 "7.7e-8; upper-bound violation 1.87% vs 3.20%.",
        "source": "Section 4.3, Table 4",
        "quoted_numbers": {"fluxnet_d_mae_e-3": 3.48, "resnet_ar_mae_e-3": 15.9,
                           "resnet_ar_econs": 2.1e-2, "fluxnet_d_econs": 7.7e-8,
                           "anchored_v_ub_fluxnet_pct": 1.87, "table4_v_ub_fluxnet_resnet_pct": 2.87,
                           "table4_v_ub_fluxnet_fno_pct": 2.01, "resnet_ar_v_ub_pct": 3.20},
        "extra_blockers": [
            "LWR traffic dataset (shock / rarefaction / blockage test cases) not released.",
            "DISCREPANCY: the anchored claim quotes V_ub = 1.87% for FluxNet-D, but Table 4 as "
            "printed reports 2.87% (ResNet backbone) and 2.01% (FNO backbone). 1.87% matches "
            "neither; the closest printed value is FNO-AR's V_ub = 1.88%. This cannot be "
            "resolved without the authors' raw numbers.",
        ],
        "what_is_covered_elsewhere": "The 'machine-precision conservation' and 'no strict dual-bound "
                                     "guarantee, near-zero empirical violations' parts are covered "
                                     "structurally by claims 1 and 6.",
    },
    5: {
        "claim": "Spinodal decomposition: FluxNet-D at 1000*dt achieves 17.3x rollout speedup "
                 "while preserving two-point correlation statistics.",
        "source": "Section 4.4, Table 5 and Figure 3",
        "quoted_numbers": {"speedup_1000dt": 17.3, "mae_1000dt_e-2": 8.39, "r": 9,
                           "rf_theo": "79^2", "erf": "19.0^2"},
        "extra_blockers": [
            "The speedup is defined relative to a GPU-accelerated explicit Cahn-Hilliard solver; "
            "no GPU is available in this environment, so the reference timing cannot be measured "
            "and the ratio is not defined on CPU.",
            "Requires training three FluxNet-D models on 50k-step phase-field trajectories "
            "(t=2000..52000, snapshots every 10dt), data not released.",
            "The two-point correlation metric S2bar(r) itself is implementable (FFT autocorrelation) "
            "but there is nothing trained to evaluate it on.",
        ],
        "what_is_covered_elsewhere": None,
    },
}

os.makedirs("results", exist_ok=True)
paper_present = os.path.exists(PAPER_TXT)
code_url_hits = None
if paper_present:
    txt = open(PAPER_TXT, encoding="utf-8", errors="ignore").read()
    code_url_hits = len([m for m in re.finditer(
        r"github\.com|zenodo|anonymous\.4open|code (is )?available", txt, re.I)])

for n, c in claims.items():
    out = {
        "claim": n,
        "command": ".venv/bin/python verify_claims345.py",
        "verdict": "inconclusive",
        "claim_text": c["claim"],
        "paper_source": c["source"],
        "quoted_numbers_not_reproduced": c["quoted_numbers"],
        "blockers": blockers_common + c["extra_blockers"],
        "covered_elsewhere": c["what_is_covered_elsewhere"],
        "code_url_hits_in_paper_text": code_url_hits,
        "toy_substitute_used": False,
        "attempt_time_cap_h": 2,
    }
    json.dump(out, open(f"results/claim{n}.json", "w"), indent=2)
    print(f"claim{n}: inconclusive ({len(out['blockers'])} blockers recorded)")
