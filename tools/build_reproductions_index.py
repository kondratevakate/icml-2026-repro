"""Build reproductions/INDEX.md: one row per paper folder, from its logbook metadata and the challenge verdicts.

Inputs: reproductions/*/**/.trackio/metadata.json (Space id and paper tag), papers.json at the repository root
(paper titles; optional) and the verdict snapshot data/verdicts_confirmation_2026-10-17/verdicts.json
(optional; verdict counts per Space). Missing optional inputs leave their columns empty.

Usage: python tools/build_reproductions_index.py
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPRO = ROOT / "reproductions"
SNAPSHOT = ROOT / "data" / "verdicts_confirmation_2026-10-17" / "verdicts.json"
sys.path.insert(0, str(ROOT / "verdict_audit"))
import analyze as A  # noqa: E402  (shared loading and verdict categories)


SKIP = {".venv", "venv", ".git", "node_modules", "repo_ref", "data", "__pycache__", ".rlib"}


def logbooks(folder: Path) -> list[dict]:
    """Logbook metadata under a paper folder; skips environments, clones of official code and data."""
    found, errors = [], []
    for here, dirs, files in os.walk(folder, onerror=errors.append):
        dirs[:] = sorted(d for d in dirs if d not in SKIP and not d.startswith("official"))
        if Path(here).name == ".trackio" and "metadata.json" in files:
            found.append(Path(here) / "metadata.json")
    if errors:
        print(f"{folder.name}: {len(errors)} unreadable paths skipped", file=sys.stderr)
    out = []
    for m in found:
        meta = json.loads(m.read_text(encoding="utf-8"))
        orid = next((t[len("paper-"):] for t in meta.get("tags", []) if t.startswith("paper-")), None)
        out.append(dict(space=meta.get("space_id"), orid=orid))
    return out


def main() -> None:
    titles = {}
    if (ROOT / "papers.json").exists():
        titles = {p["orid"]: p["title"] for p in json.loads((ROOT / "papers.json").read_text(encoding="utf-8-sig"))["papers"]}
    verdicts, snapshot_note = {}, "verdict snapshot not found; verdict columns empty"
    if SNAPSHOT.exists():
        logs, _ = A.dedupe(list(A.load_json(SNAPSHOT).values()))
        for r in logs:
            verdicts[r["space_id"]] = Counter(A.category(c.get("verdict")) for c in r.get("claims") or [])
        snapshot_note = f"verdict snapshot `{SNAPSHOT.relative_to(ROOT).as_posix()}` (SHA-256 `{A.sha256(SNAPSHOT)[:12]}…`)"
    rows, by_orid = [], Counter()
    for folder in sorted(p for p in REPRO.iterdir() if p.is_dir()):
        books = logbooks(folder) or [dict(space=None, orid=None)]
        for b in books:
            by_orid[b["orid"]] += bool(b["orid"])
            rows.append((folder.name, b))
    lines = [
        "# Challenge reproductions",
        "",
        "One folder per ICML 2026 paper reproduced for the challenge. Each folder holds the scripts, a `.trackio/`",
        "mirror of the published logbook and a `repro_*` bundle. Verdicts are the challenge judge's, counted per",
        "claim on the published logbook (verified, falsified, toy, inconclusive).",
        "",
        f"Generated by `tools/build_reproductions_index.py` from the logbook metadata and the {snapshot_note}.",
        "A Space without verdicts was not judged in that snapshot (for example, never published).",
        "",
        "| Folder | Paper | OpenReview id | Space | Claims | Verified | Falsified | Toy | Inconclusive |",
        "|---|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for name, b in rows:
        v = verdicts.get(b["space"])
        title = titles.get(b["orid"], "")
        note = f" (one of {by_orid[b['orid']]} logbooks for this paper)" if b["orid"] and by_orid[b["orid"]] > 1 else ""
        space = f"[`{b['space'].split('/')[-1]}`](https://huggingface.co/spaces/{b['space']})" if b["space"] else "no logbook"
        counts = [str(sum(v.values())), str(v["verified"]), str(v["falsified"]), str(v["toy"]), str(v["inconclusive"])] if v else [""] * 5
        lines.append(f"| [`{name}/`]({name}/) | {title}{note} | {b['orid'] or ''} | {space} | " + " | ".join(counts) + " |")
    (REPRO / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    judged = sum(1 for _, b in rows if b["space"] in verdicts)
    print(f"{len(rows)} rows, {judged} judged Spaces")


if __name__ == "__main__":
    main()
